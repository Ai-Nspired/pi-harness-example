/**
 * The convention every Worker in this account uses to talk to another one. It
 * exists so a caller does not have to read the callee's source to send a
 * message: one envelope in, one envelope out, one error shape, one version.
 *
 * Anything that wants to be reachable by its siblings should speak this. It is
 * deliberately small: nothing here knows about pi, presets or transcripts.
 */

/** The name this Worker answers to on the wire. */
export const AGENT_NAME = "op";

/** Bumped when a field changes meaning. Additive fields do not bump it. */
export const AGENT_PROTOCOL_VERSION = 1;

/** Fixed header names, so every implementation sends the same ones. */
export const PROTOCOL_HEADERS = {
  /** Protocol version the sender speaks. */
  version: "x-agent-protocol",
  /** Sender's `AGENT_NAME`, for the callee's logs. */
  from: "x-agent",
  /** Correlation id; the callee echoes it on the reply. */
  requestId: "x-agent-request-id"
} as const;

/** What a caller may post to a sibling. Only `message` is required. */
export type AgentRequest = {
  /** The sender's protocol version. Absent is read as version 1. */
  readonly version?: number;
  /** Correlation id; echoed back. Generated by the callee when missing. */
  readonly request_id?: string;
  /** Sender's agent name. */
  readonly from?: string;
  /** What to ask. */
  readonly message: string;
  /** Preset slug to run this request on, when the caller knows it. */
  readonly preset?: string;
  /** Conversation to continue; omitted means the callee's default one. */
  readonly session?: string;
};

/** Error codes, so a caller can branch without parsing prose. */
export const AGENT_ERRORS = {
  invalidRequest: "invalid_request",
  unknownPreset: "unknown_preset",
  unsupportedVersion: "unsupported_version",
  unavailable: "unavailable"
} as const;

export type AgentErrorCode =
  (typeof AGENT_ERRORS)[keyof typeof AGENT_ERRORS];

export type ParsedRequest =
  | {
      readonly ok: true;
      readonly message: string;
      readonly preset?: string;
      readonly session: string;
      readonly requestId: string;
      readonly from: string;
      readonly version: number;
      /** True when the body was a bare string or `{ message }`. */
      readonly plain: boolean;
    }
  | {
      readonly ok: false;
      readonly code: AgentErrorCode;
      readonly message: string;
      readonly requestId: string;
    };

/** Correlation id, from the body or the header, or a fresh one. */
function requestIdOf(body: Record<string, unknown>, headers: Headers): string {
  const fromBody = typeof body.request_id === "string" ? body.request_id.trim() : "";
  const fromHeader = headers.get(PROTOCOL_HEADERS.requestId)?.trim() ?? "";
  const id = fromBody || fromHeader;
  return id.length > 0 && id.length <= 200 ? id : crypto.randomUUID();
}

/**
 * Read an incoming request, accepting both the envelope and the plain shape
 * (`{ message }`) so a caller written before this convention still works.
 */
export function parseAgentRequest(body: unknown, headers: Headers): ParsedRequest {
  if (typeof body === "string") {
    const message = body.trim();
    return message
      ? {
          ok: true,
          message,
          session: "assistant",
          requestId: crypto.randomUUID(),
          from: "unknown",
          version: AGENT_PROTOCOL_VERSION,
          plain: true
        }
      : { ok: false, code: AGENT_ERRORS.invalidRequest, message: "The message was empty", requestId: crypto.randomUUID() };
  }

  if (typeof body !== "object" || body === null) {
    return {
      ok: false,
      code: AGENT_ERRORS.invalidRequest,
      message: "Send a JSON object with a `message`",
      requestId: crypto.randomUUID()
    };
  }

  const record = body as Record<string, unknown>;
  const requestId = requestIdOf(record, headers);
  const version =
    typeof record.version === "number" ? record.version : AGENT_PROTOCOL_VERSION;
  if (version > AGENT_PROTOCOL_VERSION) {
    return {
      ok: false,
      code: AGENT_ERRORS.unsupportedVersion,
      message: `This agent speaks version ${AGENT_PROTOCOL_VERSION}, not ${version}`,
      requestId
    };
  }

  const message = typeof record.message === "string" ? record.message.trim() : "";
  if (!message) {
    return {
      ok: false,
      code: AGENT_ERRORS.invalidRequest,
      message: "`message` is required and must be a non-empty string",
      requestId
    };
  }

  const preset =
    typeof record.preset === "string" ? record.preset : undefined;
  const session =
    typeof record.session === "string" && record.session.trim()
      ? record.session.trim()
      : "assistant";
  const from =
    typeof record.from === "string" && record.from.trim()
      ? record.from.trim()
      : headers.get(PROTOCOL_HEADERS.from)?.trim() || "unknown";

  return {
    ok: true,
    message,
    ...(preset === undefined ? {} : { preset }),
    session,
    requestId,
    from,
    version: AGENT_PROTOCOL_VERSION,
    plain: false
  };
}

/** Headers this Worker sends when it calls a sibling. */
export function outgoingHeaders(requestId: string): Record<string, string> {
  return {
    "content-type": "application/json",
    accept: "application/json",
    [PROTOCOL_HEADERS.version]: String(AGENT_PROTOCOL_VERSION),
    [PROTOCOL_HEADERS.from]: AGENT_NAME,
    [PROTOCOL_HEADERS.requestId]: requestId
  };
}

/** Headers this Worker returns on any agent response. */
export function responseHeaders(requestId: string): Record<string, string> {
  return {
    "cache-control": "no-store",
    [PROTOCOL_HEADERS.version]: String(AGENT_PROTOCOL_VERSION),
    [PROTOCOL_HEADERS.from]: AGENT_NAME,
    [PROTOCOL_HEADERS.requestId]: requestId
  };
}

/** A successful reply: the answer, and what produced it. */
export function successBody(options: {
  requestId: string;
  session: string;
  text: string;
  model?: string;
}) {
  return {
    version: AGENT_PROTOCOL_VERSION,
    request_id: options.requestId,
    from: AGENT_NAME,
    ok: true as const,
    session: options.session,
    text: options.text,
    ...(options.model === undefined ? {} : { model: options.model })
  };
}

/** A failure reply, with a code a caller can branch on. */
export function failureBody(
  requestId: string,
  code: AgentErrorCode,
  message: string
) {
  return {
    version: AGENT_PROTOCOL_VERSION,
    request_id: requestId,
    from: AGENT_NAME,
    ok: false as const,
    error: { code, message }
  };
}

/**
 * What this Worker offers a sibling that asks who it is. Keep it factual: a
 * caller should be able to configure itself from this card alone.
 */
export function agentCard(baseUrl: string) {
  return {
    name: AGENT_NAME,
    version: AGENT_PROTOCOL_VERSION,
    base_url: baseUrl,
    endpoints: {
      message: {
        method: "POST",
        path: "/api/assistant",
        request: {
          version: "number, optional",
          request_id: "string, optional, echoed back",
          from: "string, optional, sender name",
          message: "string, required",
          preset: "string, optional, configured preset slug",
          session: "string, optional, defaults to `assistant`"
        },
        response: {
          version: "number",
          request_id: "string",
          from: "string",
          ok: "boolean",
          session: "string",
          text: "string when ok",
          model: "string when ok and known",
          error: "{ code, message } when not ok"
        }
      },
      presets: { method: "GET", path: "/api/route" },
      health: { method: "GET", path: "/api/transcribe" }
    },
    error_codes: Object.values(AGENT_ERRORS),
    headers: {
      request_id: PROTOCOL_HEADERS.requestId,
      version: PROTOCOL_HEADERS.version,
      from: PROTOCOL_HEADERS.from
    },
    limits: {
      message_chars: 40_000,
      timeout_ms: 120_000,
      idempotency: "request_id is a correlation id, not a dedupe key"
    }
  };
}
